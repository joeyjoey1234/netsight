func LookupOUI(mac string) string {
	clean := strings.ToUpper(strings.ReplaceAll(strings.ReplaceAll(mac, ":", ""), "-", ""))
	if len(clean) < 6 {
		return ""
	}
	oui := clean[:6]
	if vendor, ok := ouiDB[oui]; ok {
		return vendor
	}
	return ""
}
